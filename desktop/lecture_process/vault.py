"""The Obsidian vault of notes: initial settings and the generated contents pages.

Layout:
  Главная.md                       generated: subjects, latest notes, lectures waiting for notes
  <Subject>/<Subject>.md           generated: table of that subject's notes
  <Subject>/<date> <title>.md      notes written by the konspekt skill (never touched here)
  <Subject>/attachments/<note>/    photos embedded in a note

Contents pages are rebuilt from the notes' front matter, so they are always complete and
never need hand edits (and are overwritten: do not write into them).
"""
import json
import os
from pathlib import Path

HOME = "Главная.md"
GENERATED = "<!-- generated by lecture_process: rebuilt automatically, edits here are lost -->"

# Obsidian settings written once, when the vault has none (the user's later changes stay).
APP_SETTINGS = {
    "attachmentFolderPath": "./attachments",
    "newFileLocation": "current",
    "alwaysUpdateLinks": True,
    "readableLineLength": True,
}


def _front(md: Path) -> dict:
    """Simple `key: value` front matter (all our notes use); lists stay as text."""
    try:
        text = md.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return {}
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    fields = {}
    for line in text[3:end].splitlines():
        if ":" in line and not line.startswith(" "):
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip().strip('"')
    return fields


def notes(vault: Path):
    """Notes with a lecture source, by subject: {subject: [(path, front matter)]}."""
    out = {}
    for md in vault.rglob("*.md"):
        if ".obsidian" in md.parts or ".trash" in md.parts:
            continue
        front = _front(md)
        if front.get("источник"):
            out.setdefault(front.get("предмет") or md.parent.name, []).append((md, front))
    for items in out.values():
        items.sort(key=lambda x: (x[1].get("дата", ""), x[0].name))
    return out


def setup(vault: Path, subjects=()):
    """Creates the vault folder, Obsidian settings (once) and a folder per known subject."""
    vault.mkdir(parents=True, exist_ok=True)
    settings = vault / ".obsidian" / "app.json"
    if not settings.exists():
        settings.parent.mkdir(exist_ok=True)
        settings.write_text(json.dumps(APP_SETTINGS, ensure_ascii=False, indent=2), encoding="utf-8")
    for s in subjects:
        (vault / s).mkdir(exist_ok=True)


def _date_ru(iso):
    return f"{iso[8:10]}.{iso[5:7]}.{iso[0:4]}" if len(iso) >= 10 else iso


def _cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def _write(path: Path, text: str):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def write_indexes(vault: Path, subjects=(), waiting=()):
    """Rebuilds every subject's contents page and Главная.md.

    [subjects]: subjects that get a page even without notes (from the glossaries).
    [waiting]: status rows of processed lectures without an up-to-date note.
    """
    by_subject = notes(vault)
    names = sorted(set(subjects) | set(by_subject) | {w["subject"] for w in waiting}, key=str.lower)
    for subject in names:
        folder = vault / subject
        folder.mkdir(exist_ok=True)
        rows = by_subject.get(subject, [])
        lines = ["---", "tags: [оглавление]", "---", GENERATED, f"# {subject}", ""]
        if rows:
            lines += ["| Дата | Конспект | Тип | Тема |", "|---|---|---|---|"]
            for md, f in reversed(rows):
                link = md.relative_to(folder).with_suffix("").as_posix()
                title = f.get("название") or md.stem
                lines.append(f"| {_date_ru(f.get('дата', ''))} | [[{link}\\|{_cell(title)}]] | "
                             f"{_cell(f.get('тип', ''))} | {_cell(f.get('тема', ''))} |")
        else:
            lines.append("Конспектов пока нет.")
        pending = [w for w in waiting if w["subject"] == subject]
        if pending:
            lines += ["", "## Ждут конспекта", ""]
            lines += [f"- {_date_ru(w['date'] or '')} {w['title']}"
                      f"{' (конспект устарел)' if w['state'] == 'changed' else ''}" for w in pending]
        _write(folder / f"{subject}.md", "\n".join(lines) + "\n")

    lines = ["---", "tags: [оглавление]", "---", GENERATED, "# Конспекты лекций", "", "## Предметы", ""]
    for subject in names:
        rows = by_subject.get(subject, [])
        last = f", последний {_date_ru(rows[-1][1].get('дата', ''))}" if rows else ""
        lines.append(f"- [[{subject}/{subject}|{subject}]] — конспектов: {len(rows)}{last}")
    latest = sorted(((f.get("дата", ""), md, f) for items in by_subject.values() for md, f in items),
                    key=lambda x: (x[0], x[1].name), reverse=True)[:10]
    if latest:
        lines += ["", "## Последние", ""]
        for date, md, f in latest:
            link = md.relative_to(vault).with_suffix("").as_posix()
            lines.append(f"- {_date_ru(date)} [[{link}|{f.get('предмет', '')} — {f.get('название') or md.stem}]]"
                         + (f": {f['тема']}" if f.get("тема") else ""))
    if waiting:
        lines += ["", "## Ждут конспекта", ""]
        lines += [f"- {_date_ru(w['date'] or '')} {w['subject']} — {w['title']}"
                  f"{' (конспект устарел)' if w['state'] == 'changed' else ''}" for w in waiting]
        lines += ["", "Конспект пишет Claude Code: `/konspekt` или «конспект по всем новым»."]
    lines += ["", "---", "Лекции записываются приложением на телефоне, забираются и обрабатываются окном «Лекции» "
              "на рабочем столе; конспекты пишет Claude Code (скилл konspekt)."]
    _write(vault / HOME, "\n".join(lines) + "\n")
